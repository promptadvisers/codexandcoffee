import Foundation

@main struct HoldChecks {
    static func main() {
        var trigger = OptionHoldTrigger()
        precondition(trigger.update(optionDown: true, otherKeyDown: false, now: 0) == .none)
        precondition(trigger.update(optionDown: true, otherKeyDown: false, now: 0.11) == .press)
        precondition(trigger.update(optionDown: true, otherKeyDown: false, now: 0.2) == .none)
        precondition(trigger.update(optionDown: false, otherKeyDown: false, now: 1) == .release)
        precondition(trigger.update(optionDown: false, otherKeyDown: false, now: 1.1) == .none)
        precondition(trigger.update(optionDown: true, otherKeyDown: true, now: 2) == .none)
        precondition(trigger.update(optionDown: true, otherKeyDown: false, now: 2.2) == .none, "Chord stays blocked until Option release")
        _ = trigger.update(optionDown: false, otherKeyDown: false, now: 3)
        _ = trigger.update(optionDown: true, otherKeyDown: false, now: 4)
        precondition(trigger.update(optionDown: true, otherKeyDown: false, now: 4.2) == .press)
        precondition(trigger.update(optionDown: true, otherKeyDown: true, now: 4.3) == .cancel)
        precondition(trigger.update(optionDown: true, otherKeyDown: false, now: 4.4) == .none)
        precondition(trigger.update(optionDown: false, otherKeyDown: false, now: 5) == .release, "Cancelled hold still clears HoldState latch")
        var boot = OptionHoldTrigger(initiallyDown: true)
        precondition(boot.update(optionDown: true, otherKeyDown: false, now: 10) == .none, "Never record an Option key already held at startup")
        _ = boot.update(optionDown: false, otherKeyDown: false, now: 11)
        _ = boot.update(optionDown: true, otherKeyDown: false, now: 12)
        precondition(boot.update(optionDown: false, otherKeyDown: false, now: 12.05) == .none, "Very short tap never requests microphone")
        var s = HoldState()
        let first = s.press()!
        precondition(s.press() == nil, "Repeat must not restart hold")
        precondition(s.release(now: 1) == .abandonPermission)
        precondition(!s.permission(first, granted: true, now: 2), "Late grant must not record after release")
        let second = s.press()!
        precondition(!s.permission(first, granted: true, now: 3), "Stale callback must not arm a later hold")
        precondition(s.permission(second, granted: true, now: 3))
        precondition(s.release(now: 3.1) == .discard, "Short tap should never submit audio")
        let third = s.press()!
        precondition(s.permission(third, granted: true, now: 4))
        precondition(s.release(now: 5) == .transcribe)
        precondition(s.release(now: 5) == .ignored, "Duplicate release must not submit twice")
        precondition(s.press() == nil, "Busy must reject a new recording")
        precondition(s.release(now: 6) == .ignored)
        precondition(s.accepts(third))
        s.cancel()
        precondition(!s.accepts(third), "Cancelled backend response must be discarded")
        let fourth = s.press()!
        s.cancel()
        precondition(s.press() == nil, "Held key must stay latched after Escape")
        precondition(!s.permission(fourth, granted: true, now: 8))
        precondition(s.release(now: 8) == .ignored)
        let fifth = s.press()!
        precondition(!s.permission(fifth, granted: false, now: 9))
        precondition(s.phase == .idle)
        precondition(s.press() == nil)
        _ = s.release(now: 9)
        let ask = s.begin(.asking)!
        precondition(s.begin(.status) == nil)
        precondition(s.press() == nil)
        s.finish()
        precondition(s.press() == nil, "Busy key press cannot become recording when Ask finishes")
        _ = s.release(now: 10)
        precondition(!s.accepts(ask))
        precondition(s.press() != nil)
        precondition(HelperTargetPolicy.eligible(role: "AXTextArea", subrole: "AXUnknown", protected: false, enabled: true))
        precondition(!HelperTargetPolicy.eligible(role: "AXTextField", subrole: "AXSecureTextField", protected: false, enabled: true))
        precondition(!HelperTargetPolicy.eligible(role: "AXSecureTextField", subrole: "AXUnknown", protected: false, enabled: true))
        precondition(HelperTargetPolicy.eligible(role: "AXTextField", subrole: nil, protected: false, enabled: true))
        precondition(!HelperTargetPolicy.eligible(role: "AXTextField", subrole: "AXUnknown", protected: true, enabled: true))
        precondition(!HelperTargetPolicy.eligible(role: "AXButton", subrole: "AXUnknown", protected: false, enabled: true))
        precondition(!HelperTargetPolicy.eligible(role: "AXTextArea", subrole: "AXUnknown", protected: false, enabled: false))
        precondition(!HelperTargetPolicy.canInsert(eligible: true, focusLost: true, sameField: true), "Returning to a field must not undo observed focus loss")
        precondition(!HelperTargetPolicy.canInsert(eligible: true, focusLost: false, sameField: false))
        precondition(HelperTargetPolicy.canInsert(eligible: true, focusLost: false, sameField: true))
        let edited = HelperTextEdit.replacing(value: "Hello world", location: 6, length: 5, text: "Alex")!
        precondition(edited.value == "Hello Alex" && edited.caret == 10)
        let unicode = HelperTextEdit.replacing(value: "A😀B", location: 3, length: 0, text: "🌍")!
        precondition(unicode.value == "A😀🌍B" && unicode.caret == 5)
        precondition(HelperTextEdit.replacing(value: "😀", location: 1, length: 0, text: "x") == nil)
        precondition(HelperTextEdit.replacing(value: "abc", location: -1, length: 0, text: "x") == nil)
        precondition(HelperTextEdit.replacing(value: "abc", location: 0, length: Int.max, text: "x") == nil)
        precondition(HelperTextEdit.replacing(value: "abc", location: 4, length: 0, text: "x") == nil)
        precondition(HelperTextEdit.replacing(value: "", location: 0, length: 0, text: "Relay hello")!.value == "Relay hello")
        precondition(HelperPasteVerification.outcome(before: "", expected: "Hello", after: "", sameField: true) == "paste_unverified", "An unchanged rich editor must never report inserted")
        precondition(HelperPasteVerification.outcome(before: "", expected: "Hello", after: "Hello", sameField: true) == "inserted_verified")
        precondition(HelperPasteVerification.outcome(before: "Hello world", expected: edited.value, after: "Hello Alex", sameField: true) == "inserted_verified")
        precondition(HelperPasteVerification.outcome(before: "A😀B", expected: unicode.value, after: "A😀🌍B", sameField: true) == "inserted_verified")
        precondition(HelperPasteVerification.outcome(before: "", expected: "Hello", after: "Hello", sameField: false) == "paste_unverified")
        precondition(HelperPasteVerification.outcome(before: nil, expected: nil, after: "Hello", sameField: true) == "paste_unverified")
        precondition(HelperPasteVerification.outcome(before: "Hello", expected: "Hello", after: "Hello", sameField: true) == "paste_unverified")
        precondition(HelperPasteVerification.restoreClipboard(written: 10, current: 10))
        precondition(!HelperPasteVerification.restoreClipboard(written: 10, current: 11), "Preserve anything copied after the paste")
        var focus = HelperFocusTracker()
        focus.observe(.same); focus.observe(.unavailable); focus.observe(.same)
        precondition(!focus.lost, "A failed AX read must not latch focus loss")
        focus.observe(.moved); focus.observe(.same)
        precondition(focus.lost, "Actual movement stays latched even after returning")
        var delayed = HelperPasteMonitor(before: "", expected: "Hello", deadline: 2.5)
        precondition(delayed.observe(after: "", focus: .same, now: 1.1) == .wait, "Do not restore the clipboard on the old one-second timer")
        precondition(delayed.observe(after: "Hello", focus: .same, now: 1.7) == .wait)
        precondition(delayed.observe(after: "Hello", focus: .same, now: 1.8) == .verified)
        var reverted = HelperPasteMonitor(before: "", expected: "Hello", deadline: 2.5)
        precondition(reverted.observe(after: "Hello", focus: .same, now: 0.1) == .wait)
        precondition(reverted.observe(after: "", focus: .same, now: 0.2) == .wait)
        precondition(reverted.observe(after: "", focus: .same, now: 2.5) == .unverified("unchanged"))
        var unknown = HelperPasteMonitor(before: "", expected: "Hello", deadline: 2.5)
        precondition(unknown.observe(after: nil, focus: .unavailable, now: 0.1) == .wait)
        precondition(unknown.observe(after: "Hello", focus: .same, now: 0.3) == .wait)
        precondition(unknown.observe(after: "Hello", focus: .same, now: 0.4) == .verified)
        var changed = HelperPasteMonitor(before: "", expected: "Hello", deadline: 2.5)
        precondition(changed.observe(after: "Hello", focus: .moved, now: 0.1) == .unverified("focus_lost_after_paste"))
        var lines = HelperPasteMonitor(before: "", expected: "A\r\nB", deadline: 2.5)
        precondition(lines.observe(after: "A\nB", focus: .same, now: 0.1) == .wait)
        precondition(lines.observe(after: "A\nB", focus: .same, now: 0.2) == .verified)
        var spaces = HelperPasteMonitor(before: "", expected: "A  B", deadline: 2.5)
        precondition(spaces.observe(after: "A B", focus: .same, now: 2.5) == .unverified("mismatch"), "Do not normalize away a wrong edit")
        precondition(HelperPasteVerification.canCancel(pasteCommitted: false))
        precondition(!HelperPasteVerification.canCancel(pasteCommitted: true), "Do not claim cancellation after sending paste")
        print("Focus uncertainty, delayed paste, transient readback, focus movement, line endings, exact whitespace and cancellation checks passed.")
        print("Verified paste checks passed: unchanged editor, exact edit, selection, emoji, focus loss, unreadable field, no-op, clipboard ownership.")
        print("Hold, target and UTF-16 selection checks passed: permission release, stale grant, repeat, short tap, release, busy latch, cancellation, denied permission.")
    }
}
